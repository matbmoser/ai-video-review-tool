"""Build the browser-only version of the review tool for GitHub Pages.

    python scripts/build_pages.py [OUT_DIR]        (default: _site)

The site is the same page as ``video-review`` serves, plus ``browser-backend.js``: videos are opened from
your disk and never uploaded, notes and screenshots are stored in the browser, and the chat calls the
Anthropic API directly with your own key. Claude Code (terminal) and the MCP server need the installed tool
and are not part of the site. Constants shared with the Python package (change types, models, the chat's
system prompt) are written to ``config.js`` so both versions stay the same.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from video_review import __version__  # noqa: E402
from video_review.claude_api import API_URL, API_VERSION, DEFAULT_MODEL, MODELS, SYSTEM_PROMPT  # noqa: E402
from video_review.store import KINDS  # noqa: E402

STATIC = ROOT / "src" / "video_review" / "static"
REPO_URL = "https://github.com/matbmoser/ai-video-review-tool"
SKIP = {"vendor/xterm"}  # the terminal needs the local server

CSP = ("default-src 'self'; img-src 'self' data: blob:; media-src 'self' blob:; style-src 'self' 'unsafe-inline'; "
       "script-src 'self'; connect-src 'self' https://api.anthropic.com; object-src 'none'; base-uri 'self'; "
       "form-action 'none'")

# (old, new) replacements in index.html; each one must match exactly once
INDEX_EDITS = [
    ('<meta charset="utf-8">',
     '<meta charset="utf-8">\n'
     f'  <meta http-equiv="Content-Security-Policy" content="{CSP}">\n'
     '  <meta name="description" content="Review videos frame by frame in your browser: pin or box the spot, '
     'describe the change, hand the review to Claude. Nothing is uploaded.">\n'
     '  <meta name="referrer" content="no-referrer">'),
    ('  <link rel="stylesheet" href="./vendor/xterm/xterm.css">\n', ''),
    ('  <script src="./app.js"></script>',
     '  <script src="./config.js"></script>\n  <script src="./browser-backend.js"></script>\n'
     '  <script src="./app.js"></script>'),
    ('Uploading a new render with the same file name keeps its notes.',
     'The video stays on your computer, nothing is uploaded. Opening a new render with the same file name '
     'keeps its notes.'),
    ('title="Upload a video (or drop it onto the page)"',
     'title="Open a video from your computer (or drop it onto the page). It is not uploaded."'),
    ('<div class="dropzone" id="dropzone" hidden><div>Drop to upload</div></div>',
     '<div class="dropzone" id="dropzone" hidden><div>Drop to open</div></div>'),
    ('Kept only in the memory of the local review server (never saved, never sent to\n'
     '          the page again) and sent only to api.anthropic.com. '
     'Or start the tool with <code>ANTHROPIC_API_KEY</code> set.',
     'Kept only in the memory of this page (never saved: paste it again after a reload) and sent only to\n'
     '          api.anthropic.com, directly from your browser.'),
    ('        <div class="credits small muted">',
     '        <div class="small muted browser-note">Browser version: notes are saved in this browser, the video is '
     'never uploaded. For Claude Code next to the video and the MCP server, '
     f'<a href="{REPO_URL}#quick-start" target="_blank" rel="noopener noreferrer">install the tool</a>.</div>\n'
     '        <div class="credits small muted">'),
]


def build(out: Path) -> Path:
    if out.exists():
        shutil.rmtree(out)
    for src in sorted(STATIC.rglob("*")):
        rel = src.relative_to(STATIC).as_posix()
        if src.is_dir() or any(rel == s or rel.startswith(s + "/") for s in SKIP):
            continue
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix in (".html", ".js", ".css") and "vendor/" not in rel:
            dst.write_text(src.read_text(encoding="utf-8").replace("/static/", "./"), encoding="utf-8")
        else:
            shutil.copyfile(src, dst)

    index = out / "index.html"
    html = index.read_text(encoding="utf-8")
    for old, new in INDEX_EDITS:
        if html.count(old) != 1:
            raise SystemExit(f"build_pages: expected exactly one {old[:60]!r} in index.html")
        html = html.replace(old, new)
    if re.search(r"""(src|href)="/(?!/)""", html):
        raise SystemExit("build_pages: index.html still has root-relative links")
    index.write_text(html, encoding="utf-8")

    config = {
        "version": __version__, "kinds": list(KINDS), "models": MODELS, "defaultModel": DEFAULT_MODEL,
        "systemPrompt": SYSTEM_PROMPT, "apiUrl": API_URL, "apiVersion": API_VERSION, "repository": REPO_URL,
    }
    (out / "config.js").write_text(
        "/* generated by scripts/build_pages.py from the Python package: do not edit */\n"
        f"window.VideoReviewStatic = {json.dumps(config, indent=2, ensure_ascii=False)};\n", encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    return out


if __name__ == "__main__":
    target = build(Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "_site").resolve())
    print(f"built {target}")
